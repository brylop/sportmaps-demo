const lib = await import('../lib.mjs');
const OUT = process.argv[2];
const browser = await lib.launch();
const context = await browser.newContext({ viewport: lib.VIEWPORT, deviceScaleFactor: lib.DSF, isMobile: true, hasTouch: true, locale: 'es-CO', timezoneId: 'America/Bogota', storageState: `${OUT}/state-reg.json` });
const page = await context.newPage(); const errors = [];
page.on('response', (r) => { if (r.status() >= 400) errors.push(`[http ${r.status()}] ${r.url().split('?')[0]}`); });
page.on('pageerror', (e) => errors.push(e.message));
const txt = () => page.evaluate(() => document.body.innerText.replace(/\n+/g,' | ').slice(0,900));
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` });
await lib.go(page, '/onboarding/parent', 3000);
await shot('j4-onb-paso1');
await page.getByRole('button', { name: 'Siguiente' }).click();
await lib.settle(page, 1500);
await shot('j5-onb-paso2');
console.log('5>', await txt());
await page.getByRole('button', { name: /Unirme a mi escuela/ }).click();
await lib.settle(page, 5000);
console.log('URL', page.url());
await shot('j6-unirse-confirmar');
console.log('6>', await txt());
await page.getByRole('button', { name: 'Sí, es mi escuela' }).click();
await lib.settle(page, 1000);
await page.getByRole('radio', { name: /Para mi hijo/ }).click();
await page.fill('#join-name', 'Mateo Pardo Demo');
await page.fill('#join-dob', '2014-05-10');
await page.fill('#join-cat', 'Fútbol Sub-12');
await lib.settle(page, 500);
await shot('j7-unirse-para-quien');
await page.getByRole('button', { name: 'Enviar solicitud' }).click();
await lib.settle(page, 4000);
await shot('j8-unirse-enviada');
console.log('8>', await txt());
await lib.go(page, '/dashboard', 4000);
await shot('j9-inicio-con-solicitud');
console.log('9>', await txt());
await lib.go(page, '/children', 3500);
await shot('j10-hijos-con-solicitud');
console.log('10>', await txt());
await context.storageState({ path: `${OUT}/state-reg.json` });
console.log(errors.join(' ## '));
await browser.close();
