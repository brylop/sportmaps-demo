const lib = await import('../lib.mjs');
const OUT = process.argv[2];
const browser = await lib.launch();
const { page, errors } = await lib.newSession(browser, 'gerencia@demo.sportmaps.co', { desktop: true });
await lib.go(page, '/students?bandeja=por-asignar', 6000);
const card = page.locator('li, div.rounded-xl, div.rounded-lg').filter({ hasText: 'Mateo Pardo Demo' }).filter({ has: page.getByRole('button', { name: 'Asignar' }) }).last();
await card.getByRole('button', { name: 'Asignar' }).click();
await lib.settle(page, 2000);
const dlg = page.getByRole('dialog');
await dlg.getByRole('combobox').first().click();
await page.getByRole('option', { name: 'Fútbol — Sub-12' }).click();
await lib.settle(page, 1500);
await page.screenshot({ path: `${OUT}/o2-dialogo-asignar.png` });
console.log('D>', (await dlg.innerText()).replace(/\n+/g,' | '));
await dlg.getByRole('button', { name: 'Asignar' }).click();
await lib.settle(page, 8000);
await page.screenshot({ path: `${OUT}/o3-tras-asignar.png` });
console.log('T>', (await page.evaluate(() => document.body.innerText)).match(/(Asignad|Inscrit|Falta inscribir|No se pudo)[^|\n]{0,200}/g));
console.log(errors.join(' ## '));
await browser.close();
