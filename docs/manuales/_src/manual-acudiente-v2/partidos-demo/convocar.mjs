const lib = await import('../lib.mjs');
const [OUT, MATCH, TAG] = process.argv.slice(2);
const browser = await lib.launch();
const { page, errors } = await lib.newSession(browser, 'gerencia@demo.sportmaps.co', { desktop: true });
await lib.go(page, `/partidos/${MATCH}?paso=convocar`, 4000);
const btn = page.getByRole('button', { name: /^Convocar (a|y avisar)/ });
console.log('btn', await btn.textContent());
await btn.click();
await lib.settle(page, 13000);
await page.screenshot({ path: `${OUT}/${TAG}-convocado.png`, fullPage: true });
console.log((await page.evaluate(() => document.querySelector('main').innerText)).replace(/\n+/g,' | ').slice(0,800));
console.log(errors.join('\n'));
await browser.close();
