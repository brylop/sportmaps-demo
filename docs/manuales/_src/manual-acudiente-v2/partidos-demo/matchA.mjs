const lib = await import('../lib.mjs');
const OUT = process.argv[2];
const TEAM = '658d014e-26b9-44dd-bfde-8eed0a3a14ac';
const browser = await lib.launch();
const { page, errors } = await lib.newSession(browser, 'gerencia@demo.sportmaps.co', { desktop: true });
await lib.go(page, `/partidos/nuevo?equipo=${TEAM}`, 3500);
await page.fill('#pf-rival', 'Deportivo Arrayanes');
await page.fill('#pf-fecha', '2026-10-24');
await page.fill('#pf-hora', '09:00');
await page.fill('#pf-lugar', 'Cancha fútbol 11, Club Campestre');
await lib.settle(page, 500);
await page.screenshot({ path: `${OUT}/A1.png`, fullPage: true });
const b = page.getByRole('button', { name: /registrar el resultado/ });
console.log('btn', await b.textContent());
await b.click();
await page.waitForURL(/\/partidos\/[0-9a-f-]{36}/, { timeout: 20000 });
console.log('URL', page.url());
await lib.settle(page, 4000);
await page.screenshot({ path: `${OUT}/A2.png`, fullPage: true });
console.log((await page.evaluate(() => document.querySelector('main').innerText)).replace(/\n+/g,' | ').slice(0,1200));
console.log(errors.join('\n'));
await browser.close();
