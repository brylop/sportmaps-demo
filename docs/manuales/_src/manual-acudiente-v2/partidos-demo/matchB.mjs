// Crea el partido próximo (B) del equipo de Tomás y lo convoca, como owner, por la UI.
const lib = await import('../lib.mjs');
const OUT = process.argv[2];
const TEAM = '658d014e-26b9-44dd-bfde-8eed0a3a14ac';
const browser = await lib.launch();
const { page, errors } = await lib.newSession(browser, 'gerencia@demo.sportmaps.co', { desktop: true });
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png`, fullPage: true });
await lib.go(page, `/partidos/nuevo?equipo=${TEAM}`, 3500);
await page.fill('#pf-rival', 'Halcones FC');
await page.fill('#pf-fecha', '2026-10-31');
await page.fill('#pf-hora', '10:00');
await page.fill('#pf-lugar', 'Cancha fútbol 11, Club Campestre');
await page.fill('#pf-notas', 'Llegar 9:15 a. m. con uniforme blanco y canilleras.');
await shot('B1-programar');
await page.getByRole('button', { name: 'Programar y convocar' }).click();
await page.waitForURL(/\/partidos\/[0-9a-f-]{36}/, { timeout: 20000 });
console.log('URL', page.url());
await lib.settle(page, 4000);
await shot('B2-convocar');
const btn = page.getByRole('button', { name: /Convocar/ }).first();
console.log('btn', await btn.textContent());
await btn.click();
await lib.settle(page, 12000);
await shot('B3-convocado');
console.log((await page.evaluate(() => document.body.innerText)).replace(/\n+/g,' | ').slice(0,1500));
console.log(errors.join('\n'));
await browser.close();
